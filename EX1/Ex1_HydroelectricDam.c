#include<stdio.h>
#define G 9.80   //Gravitational constant
#define E 0.90  //90% conversion efficiency
#define D 1000.0 //Water Density
#define W_T_MW 1000000.0 //1 mw = 10^6 w


int main(void)
{
	float h;//h=height of the dam
	float f;//f= Flow rate of water
        float p;//p=power
	float m;//m=mass
        float w;//w=work
	float pw;//power in watts
        float pmw;//power in mega watts
        
	printf("Enter the height of the dam: ");
	scanf("%f", &h);

	printf("Enter the flow rate of water: ");
	scanf("%f", &f);

        m = f * D; //calculating mass flowing per second

	w = m * G * h; //calculating work done per second by gravity
        
        pw = E * w; //calculating power produced with 90% efficiency
        
	pmw = pw / W_T_MW; //converting watts to mega watts
        
	printf("Predicted power generated by the hydroelectric dam:  %.2f megawatts\n",pmw);

	return 0;

		  
      
        






 

















}
